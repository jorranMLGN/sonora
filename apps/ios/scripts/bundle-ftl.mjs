// Copies every assets/i18n/<locale>/main.ftl of the repo into src/generated/ftl.ts, so the app
// ships the same Fluent sources as the desktop client. Run by the `prebuild:ftl` npm script.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "..", "..", "..", "assets", "i18n");
const target = resolve(here, "..", "src", "generated", "ftl.ts");

const locales = readdirSync(source, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(source, entry.name, "main.ftl")))
  .map((entry) => entry.name)
  .sort();

if (!locales.includes("en-US")) {
  console.error("bundle-ftl: assets/i18n/en-US/main.ftl is missing");
  process.exit(1);
}

const entries = locales.map(
  (locale) =>
    `  ${JSON.stringify(locale)}: ${JSON.stringify(readFileSync(join(source, locale, "main.ftl"), "utf8"))},`,
);

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/bundle-ftl.mjs from assets/i18n. Do not edit.\n` +
    `export const ftl: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);

console.log(`bundle-ftl: ${locales.length} locales`);
